import assert from "node:assert/strict";
import { mkdir, mkdtemp, readFile, readdir, realpath, rename, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import electronPath from "electron";
import { PDFDocument } from "pdf-lib";

const playwright = await import(process.env.DYNOTE_PLAYWRIGHT_MODULE || "playwright");
const electron = playwright._electron ?? playwright.default._electron;
const root = await realpath(await mkdtemp(path.join(tmpdir(), "dynote-readable-runtime-")));
const profile = path.join(root, "profile"), vault = path.join(root, "vault"), cache = path.join(root, "cache");
const control = "# PRIVATE_VAULT_MARKER\n\nKeep the selected note untouched.\n";
let app, page;
const errors = [], samples = new Map();
try {
  for (const directory of [profile, vault, cache]) await mkdir(directory);
  await writeFile(path.join(profile, "settings.json"), JSON.stringify({ vaultRoot: vault }));
  await writeFile(path.join(vault, "Control.md"), control);
  samples.set("외부.MD", Buffer.from('# 외부 Markdown\n\n**굵게**\n\n| 항목 | 상태 |\n| --- | --- |\n| SWRS | 확인 |\n\n```js\nconst value = 1;\n```\n\n<script>window.readablePwn = true</script>'));
  samples.set("문자열.txt", Buffer.from('<script>window.readablePwn = true</script>\n한글 원문'));
  samples.set("source.py", Buffer.from('print("source preview")'));
  samples.set("이미지.png", Buffer.from("89504e470d0a1a0a0000000d4948445200000001000000010804000000b51c0c020000000b4944415478da6364f80f00010501012718e3660000000049454e44ae426082", "hex"));
  const pdf = await PDFDocument.create(); pdf.addPage().drawText("External PDF preview");
  samples.set("문서.pdf", Buffer.from(await pdf.save()));
  const wav = Buffer.alloc(44 + 1600);
  wav.write("RIFF"); wav.writeUInt32LE(wav.length - 8, 4); wav.write("WAVEfmt ", 8); wav.writeUInt32LE(16, 16);
  wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22); wav.writeUInt32LE(8000, 24); wav.writeUInt32LE(16000, 28);
  wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34); wav.write("data", 36); wav.writeUInt32LE(1600, 40);
  samples.set("녹음.wav", wav);
  samples.set("보드.canvas", Buffer.from(JSON.stringify({ nodes: [{ id: "a", type: "text", text: "외부 Canvas 메모", x: 0, y: 0, width: 300, height: 180 }], edges: [] })));
  samples.set("목록.base", Buffer.from("views:\n  - type: table\n    name: 외부 목록\n"));
  samples.set("binary.xlsx", Buffer.from([80, 75, 0, 1, 255]));
  for (const [name, bytes] of samples) await writeFile(path.join(root, name), bytes);
  app = await electron.launch({ executablePath: process.env.DYNOTE_EXECUTABLE || electronPath, args: process.env.DYNOTE_EXECUTABLE ? [] : ["."], env: { ...process.env, OPEN_NOTES_DATA: profile } });
  page = await app.firstWindow(); page.setDefaultTimeout(10000);
  page.on("pageerror", error => errors.push(error.message));
  await page.getByRole("button", { name: "파일 목록", exact: true }).click();
  await page.locator(".file-tree").getByRole("button", { name: "Control", exact: true }).click();
  await page.locator(".cm-content").waitFor();
  const initialVault = await page.evaluate(async () => (await window.notes.snapshot()).value.id);
  await app.evaluate(({ app, dialog, shell }, { source, cache }) => {
    app.setPath("temp", cache);
    dialog.showOpenDialog = async (_window, options) => {
      globalThis.externalFileFilters = options.filters;
      return { canceled: false, filePaths: [source] };
    };
    shell.openPath = async file => { globalThis.openedExternalSource = file; return ""; };
  }, { source: path.join(root, "외부.MD"), cache });
  await page.getByRole("button", { name: "파일 열기", exact: true }).click();
  const markdown = page.getByRole("dialog", { name: "외부.MD", exact: true });
  await markdown.getByRole("heading", { name: "외부 Markdown", exact: true }).waitFor();
  await markdown.getByRole("table").getByText("SWRS").waitFor();
  await markdown.locator("strong").getByText("굵게", { exact: true }).waitFor();
  await markdown.locator("pre code").getByText("const value = 1;", { exact: true }).waitFor();
  assert.notEqual(await page.evaluate(() => window.readablePwn), true);
  assert.ok((await app.evaluate(() => globalThis.externalFileFilters)).some(filter => filter.extensions.includes("md")));
  await markdown.getByRole("button", { name: "원본을 기본 앱에서 열기", exact: true }).click();
  assert.equal(await app.evaluate(() => globalThis.openedExternalSource), path.join(root, "외부.MD"));
  const updated = Buffer.from("# 갱신된 Markdown\n\n외부 저장 반영\n");
  await writeFile(path.join(root, "외부.MD.tmp"), updated); await rename(path.join(root, "외부.MD.tmp"), path.join(root, "외부.MD"));
  samples.set("외부.MD", updated);
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].emit("focus"));
  await markdown.getByRole("heading", { name: "갱신된 Markdown", exact: true }).waitFor();
  await mkdir("output/playwright", { recursive: true });
  await page.screenshot({ path: "output/playwright/external-markdown-open.png" });
  await markdown.getByRole("button", { name: "닫기", exact: true }).click();
  await page.evaluate(() => { const input = document.createElement("input"); input.id = "readable-file-input"; input.type = "file"; document.body.append(input); });
  const drop = async name => {
    await page.locator("#readable-file-input").setInputFiles(path.join(root, name));
    await page.evaluate(() => {
      const dataTransfer = new DataTransfer(); dataTransfer.items.add(document.querySelector("#readable-file-input").files[0]);
      document.querySelector(".cm-content").dispatchEvent(new DragEvent("drop", { dataTransfer, bubbles: true, cancelable: true }));
    });
    return page.getByRole("dialog", { name, exact: true });
  };
  let dialog = await drop("문자열.txt");
  await dialog.getByLabel("텍스트 미리보기").getByText('<script>window.readablePwn = true</script>\n한글 원문', { exact: true }).waitFor();
  assert.equal(await dialog.locator("script").count(), 0);
  dialog = await drop("source.py");
  await dialog.getByLabel("텍스트 미리보기").getByText('print("source preview")', { exact: true }).waitFor();
  assert.equal(await dialog.getByRole("button", { name: "원본을 기본 앱에서 열기" }).count(), 0);
  dialog = await drop("이미지.png");
  const image = dialog.getByRole("img", { name: "이미지.png" }); await image.waitFor();
  await page.waitForFunction(() => document.querySelector(".external-file-image")?.naturalWidth === 1);
  dialog = await drop("문서.pdf");
  await dialog.getByLabel("PDF 텍스트", { exact: true }).getByText("External PDF preview").waitFor();
  assert.equal(await dialog.getByRole("button", { name: "페이지 링크 복사", exact: true }).count(), 0);
  dialog = await drop("녹음.wav");
  await dialog.getByLabel("오디오 재생").waitFor();
  await page.waitForFunction(() => document.querySelector('audio[aria-label="오디오 재생"]')?.duration > 0);
  dialog = await drop("보드.canvas");
  await dialog.getByRole("textbox", { name: "메모 a", exact: true }).waitFor();
  assert.equal(await dialog.getByRole("textbox", { name: "메모 a", exact: true }).inputValue(), "외부 Canvas 메모");
  assert.equal(await dialog.getByRole("textbox", { name: "메모 a", exact: true }).evaluate(element => element.readOnly), true);
  assert.equal(await dialog.getByRole("button", { name: "메모 추가", exact: true }).isDisabled(), true);
  dialog = await drop("목록.base");
  await dialog.getByLabel("Bases 보기").waitFor();
  await dialog.getByRole("table").waitFor();
  assert.equal(await dialog.getByText("PRIVATE_VAULT_MARKER").count(), 0);
  await dialog.getByText("원문 보기", { exact: true }).click();
  await dialog.locator("pre").getByText(/외부 목록/).waitFor();
  await drop("binary.xlsx");
  await page.getByRole("dialog", { name: "파일 열기", exact: true }).getByRole("status").getByText(/UTF-8/).waitFor();
  await page.keyboard.press("Escape");
  for (const [name, bytes] of samples) assert.deepEqual(await readFile(path.join(root, name)), bytes);
  assert.equal(await readFile(path.join(vault, "Control.md"), "utf8"), control);
  assert.equal(await page.evaluate(async () => (await window.notes.snapshot()).value.id), initialVault);
  assert.equal((await readdir(vault)).some(name => /\.(png|pdf|wav|canvas|base|docx)$/i.test(name)), false);
  assert.deepEqual(errors, []);
  await app.close(); app = null;
  assert.deepEqual(await readdir(cache), []);
  await writeFile("output/playwright/readable-file-open.json", JSON.stringify({ passed: true, kinds: ["markdown", "text", "source", "image", "pdf", "audio", "canvas", "base"], originalPreserved: true, vaultPreserved: true, temporaryCleanup: true }, null, 2) + "\n");
  console.log("Readable file menu/drop, Markdown render/refresh, escaped text, image/PDF/audio, read-only Canvas/Bases and cleanup passed.");
} finally {
  if (app) { await app.evaluate(({ app }) => app.exit(0)).catch(() => {}); await app.close().catch(() => {}); }
  await rm(root, { recursive: true, force: true });
}
